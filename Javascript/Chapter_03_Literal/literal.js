let age = 25; // number literal
let name = "Alice"; // string literal
let isStudent = true; // boolean literal
let nullValue = null; // null literal   
let undefinedValue; // undefined literal (implicitly assigned)
let binary = 0b1010; // binary literal (10 in decimal)  
let octal = 0o12; // octal literal (10 in decimal)
let hexadecimal = 0xA; // hexadecimal literal (10 in decimal)  
let float = 3.14; // floating-point literal 
console.log("Age:", age);
console.log("Name:", name);
console.log("Is Student:", isStudent);
console.log("Null Value:", nullValue);
console.log("Undefined Value:", undefinedValue);
console.log("Binary Literal (0b1010):", binary);
console.log("Octal Literal (0o12):", octal);
console.log("Hexadecimal Literal (0xA):", hexadecimal);
console.log("Float Literal:", float);
